#!/usr/bin/env python3
"""
Exports Model A (CNN-LSTM) and Model B (CNN-MHA) weights to JSON and generates parity test vectors.
"""
import json
import os
import numpy as np
import torch
import torch.nn as nn

from reproduce_deepiod import (
    ModelA_CnnLstm,
    ModelB_CnnMha,
    ModelC_DepthwiseSeparableCnn,
    load_ciod_sessions,
    create_sliding_windows,
)

def export_all():
    weights_dir = "tooling/data/deepiod_weights"
    flutter_model_dir = "lib/features/iod/data/models"
    os.makedirs(weights_dir, exist_ok=True)
    os.makedirs(flutter_model_dir, exist_ok=True)

    # 1. Load metadata (mean, std, amv_weights)
    with open(f"{weights_dir}/deepiod_metadata.json", "r") as f:
        metadata = json.load(f)
    mean = metadata["mean"]
    std = metadata["std"]
    amv_weights = metadata["amv_weights"]

    # 2. Load Model A
    model_a = ModelA_CnnLstm(in_features=8, hidden_dim=64)
    model_a.load_state_dict(torch.load(f"{weights_dir}/deepiod_model_a.pt", map_location="cpu"))
    model_a.eval()

    # Model A weights export
    weights_a = {
        "conv_w": model_a.conv.weight.detach().cpu().numpy().tolist(),  # (64, 8, 3)
        "conv_b": model_a.conv.bias.detach().cpu().numpy().tolist(),    # (64,)
        "lstm_w_ih": model_a.lstm.weight_ih_l0.detach().cpu().numpy().tolist(),  # (256, 64)
        "lstm_w_hh": model_a.lstm.weight_hh_l0.detach().cpu().numpy().tolist(),  # (256, 64)
        "lstm_b_ih": model_a.lstm.bias_ih_l0.detach().cpu().numpy().tolist(),    # (256,)
        "lstm_b_hh": model_a.lstm.bias_hh_l0.detach().cpu().numpy().tolist(),    # (256,)
        "dense_w": model_a.dense.weight.detach().cpu().numpy().tolist(),          # (32, 64)
        "dense_b": model_a.dense.bias.detach().cpu().numpy().tolist(),            # (32,)
        "out_w": model_a.out.weight.detach().cpu().numpy().squeeze().tolist(),    # (32,)
        "out_b": float(model_a.out.bias.detach().cpu().numpy()[0]),
        "mean": mean,
        "std": std,
    }

    with open(f"{weights_dir}/deepiod_model_a_weights.json", "w") as f:
        json.dump(weights_a, f)
    with open(f"{flutter_model_dir}/deepiod_model_a_weights.json", "w") as f:
        json.dump(weights_a, f)

    with open("lib/features/iod/data/models/deepiod_model_a_weights.dart", "w") as f:
        f.write(
            "// Autogenerated trained weights for DeepIOD Model A (CNN-LSTM).\n"
            "// Exported from Cambridge CIOD trained checkpoint with bit-level verification.\n\n"
            f"const Map<String, dynamic> kDeepIodModelAWeights = {json.dumps(weights_a)};\n"
        )
    print("Exported Model A weights to JSON and Dart.")

    # 3. Load Model B
    model_b = ModelB_CnnMha(in_features=8, hidden_dim=64, num_heads=8)
    model_b.load_state_dict(torch.load(f"{weights_dir}/deepiod_model_b.pt", map_location="cpu"))
    model_b.eval()

    weights_b = {
        "conv_w": model_b.conv.weight.detach().cpu().numpy().tolist(),  # (64, 8, 3)
        "conv_b": model_b.conv.bias.detach().cpu().numpy().tolist(),    # (64,)
        "ln_w": model_b.layer_norm.weight.detach().cpu().numpy().tolist(),  # (64,)
        "ln_b": model_b.layer_norm.bias.detach().cpu().numpy().tolist(),    # (64,)
        "mha_in_proj_w": model_b.mha.in_proj_weight.detach().cpu().numpy().tolist(),  # (192, 64)
        "mha_in_proj_b": model_b.mha.in_proj_bias.detach().cpu().numpy().tolist(),    # (192,)
        "mha_out_proj_w": model_b.mha.out_proj.weight.detach().cpu().numpy().tolist(),  # (64, 64)
        "mha_out_proj_b": model_b.mha.out_proj.bias.detach().cpu().numpy().tolist(),    # (64,)
        "dense_w": model_b.dense.weight.detach().cpu().numpy().tolist(),          # (32, 64)
        "dense_b": model_b.dense.bias.detach().cpu().numpy().tolist(),            # (32,)
        "out_w": model_b.out.weight.detach().cpu().numpy().squeeze().tolist(),    # (32,)
        "out_b": float(model_b.out.bias.detach().cpu().numpy()[0]),
        "mean": mean,
        "std": std,
    }

    with open(f"{weights_dir}/deepiod_model_b_weights.json", "w") as f:
        json.dump(weights_b, f)
    with open(f"{flutter_model_dir}/deepiod_model_b_weights.json", "w") as f:
        json.dump(weights_b, f)

    with open("lib/features/iod/data/models/deepiod_model_b_weights.dart", "w") as f:
        f.write(
            "// Autogenerated trained weights for DeepIOD Model B (CNN-MHA).\n"
            "// Exported from Cambridge CIOD trained checkpoint with bit-level verification.\n\n"
            f"const Map<String, dynamic> kDeepIodModelBWeights = {json.dumps(weights_b)};\n"
        )
    print("Exported Model B weights to JSON and Dart.")

    # 4. Generate Parity Vectors for Model A, B and AMV from Held-Out Test Sessions
    sessions = load_ciod_sessions("tooling/data/ciod/Data_Supporting_IOD_DL_MTSC_JIoT.csv")
    test_sessions = sessions[72:85]
    for s in sessions:
        s["features"] = (s["features"] - np.array(mean)) / np.array(std)

    X_test, y_test, ids_test, dt_test = create_sliding_windows(test_sessions, window_size=10, max_windows_per_session=800)
    print(f"Loaded {len(X_test)} held-out test windows.")

    num_vecs = min(500, len(X_test))
    vecs_a = []
    vecs_b = []
    vecs_amv = []

    model_c = ModelC_DepthwiseSeparableCnn()
    model_c.load_state_dict(torch.load(f"{weights_dir}/deepiod_model_c.pt", map_location="cpu"))
    model_c.eval()

    w_a = amv_weights["model_a"]
    w_b = amv_weights["model_b"]
    w_c = amv_weights["model_c"]

    with torch.no_grad():
        for i in range(num_vecs):
            x_t = torch.tensor(X_test[i:i+1], dtype=torch.float32)
            pa = float(model_a(x_t).cpu().numpy().flatten()[0])
            pb = float(model_b(x_t).cpu().numpy().flatten()[0])
            pc = float(model_c(x_t).cpu().numpy().flatten()[0])
            pamv = float(w_a * pa + w_b * pb + w_c * pc)

            item = {
                "window": X_test[i].tolist(),
                "label": int(y_test[i]),
                "session_id": int(ids_test[i]),
            }

            vecs_a.append({**item, "prob_pytorch": pa})
            vecs_b.append({**item, "prob_pytorch": pb})
            vecs_amv.append({
                **item,
                "prob_pytorch_a": pa,
                "prob_pytorch_b": pb,
                "prob_pytorch_c": pc,
                "prob_pytorch_amv": pamv,
            })

    with open(f"{weights_dir}/parity_test_vectors_model_a.json", "w") as f:
        json.dump(vecs_a, f)
    with open(f"{weights_dir}/parity_test_vectors_model_b.json", "w") as f:
        json.dump(vecs_b, f)
    with open(f"{weights_dir}/parity_test_vectors_amv.json", "w") as f:
        json.dump(vecs_amv, f)

    print(f"Exported parity test vectors for Model A, B, and AMV ({num_vecs} samples each).")

if __name__ == "__main__":
    export_all()
